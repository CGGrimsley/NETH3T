#!/usr/bin/env python3
"""Convert assets/brushbeater_logo.webp into src/ui/logo.h (RGB565, 160x160).

The logo is gold on white; white becomes the UI background (#0B0D12) so the
gold sits on the dark boot screen. Run from the repo root:
    python3 tools/make_logo.py
"""
from PIL import Image

SIZE = 160
BG = (0x0B, 0x0D, 0x12)
GOLD = (0xE5, 0xC1, 0x4E)

src = Image.open("assets/brushbeater_logo.webp").convert("RGBA")
flat = Image.new("RGBA", src.size, (255, 255, 255, 255))
flat.alpha_composite(src)  # transparent areas count as white background
img = flat.convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
words = []
for r, g, b in list(img.getdata()) if not hasattr(img, "get_flattened_data") else img.get_flattened_data():
    # Coverage: 0 on white, 1 on full gold (blue channel drops most)
    t = max(0.0, min(1.0, (255 - b) / (255 - GOLD[2])))
    c = [round(BG[i] + (GOLD[i] - BG[i]) * t) for i in range(3)]
    words.append(((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3))

with open("src/ui/logo.h", "w") as f:
    f.write("#pragma once\n// Generated by tools/make_logo.py from assets/brushbeater_logo.webp. Do not edit.\n")
    f.write("#include <cstdint>\n\n")
    f.write(f"constexpr int kLogoW = {SIZE}, kLogoH = {SIZE};\n")
    f.write("const uint16_t kLogo[kLogoW * kLogoH] = {\n")
    for i in range(0, len(words), 16):
        f.write("  " + ", ".join(f"0x{w:04X}" for w in words[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"wrote src/ui/logo.h ({len(words) * 2} bytes)")
